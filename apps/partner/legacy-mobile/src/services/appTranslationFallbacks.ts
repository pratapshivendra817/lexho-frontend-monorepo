export function getFallbackTranslations(locale: string | null | undefined): Record<string, string> {
  const normalized = String(locale ?? "").trim().toLowerCase();
  if (!normalized) return {};

  const family = normalized.split("-")[0];
  const translations = LANGUAGE_FALLBACKS_BY_FAMILY[family];
  return translations ? { ...translations } : {};
}
