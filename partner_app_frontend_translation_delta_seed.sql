INSERT INTO translation_catalog (locale_code, translation_key, translation_value, version, created_at, updated_at)
SELECT 'en-IN', translation_key, english_value, 1, NOW(6), NOW(6)
FROM partner_app_frontend_translation_delta_seed
ON DUPLICATE KEY UPDATE
    translation_value = VALUES(translation_value),
    version = GREATEST(version, VALUES(version)),
    updated_at = NOW(6);

INSERT INTO translation_catalog (locale_code, translation_key, translation_value, version, created_at, updated_at)
SELECT language.code, seed.translation_key, seed.english_value, 1, NOW(6), NOW(6)
FROM supported_languages language
CROSS JOIN partner_app_frontend_translation_delta_seed seed
WHERE language.code IN ('en-IN', 'mr-IN', 'hi-IN', 'gu-IN', 'ta-IN', 'te-IN', 'bn-IN', 'kn-IN', 'ml-IN')
ON DUPLICATE KEY UPDATE
    translation_value = translation_catalog.translation_value,
    version = translation_catalog.version,
    updated_at = translation_catalog.updated_at;

